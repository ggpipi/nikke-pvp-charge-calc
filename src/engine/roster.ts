export interface RosterCharacter {
  id: string;
  name: string;
  aliases?: string[];
  burst: BurstStage;
  weapon: WeaponType;
  element: ElementType;
  manufacturer: ManufacturerType;
  initC: number; // 基础蓄力厘秒 (RL/SR: 100/150/200; 非蓄力武器为 0)
  inputType: "UP" | "DOWN_Charge" | "DOWN";
  baseChargeRate: number; // 单次命中基础充能 (%)
  hitsPerShot: number; // 非蓄力武器每发弹片/命中数，或蓄力武器单发命中的有效单位数(本体+掩体)
  splashTargets: number; // RL 溅射命中的角色数 (1=单体, 2=标准P1-P2, 3=宽范围P1-P3)
  fastProjectile?: boolean; // 是否为快速/连射弹道
  attackInterval60: number; // 非蓄力武器单发间隔(60fps); 蓄力武器为基准蓄力帧(60/92/122)
  magSize: number; // 弹匣容量
  reloadFrames60: number; // 换弹帧数(60fps)
  immuneToClearableBuffs?: boolean;
  special: SpecialBehavior;
  pvpRoleNote: string;
  fixedHighlight?: boolean; // 标注为源码重点修正角色
}

